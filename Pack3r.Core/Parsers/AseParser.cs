using Pack3r.Extensions;
using Pack3r.IO;
using Pack3r.Logging;
using Pack3r.Models;

namespace Pack3r.Parsers;

public partial class AseParser(
    ILogger<AseParser> logger,
    ILineReader reader) : IReferenceParser
{
    public string Description => "model";

    public bool CanParse(ReadOnlyMemory<char> resource) => resource.EndsWithF(".ase");

    public ResourceList? Parse(IAsset asset, CancellationToken cancellationToken)
    {
        ResourceList resources = [];

        foreach (var line in reader.ReadLines(asset, cancellationToken))
        {
            ReadOnlySpan<char> span = line.Value;

            if (span.ContainsWordFollowedByWhitespace("*COMMENT"))
            {
                if (span.IndexOf("Generated by Q3Map2", StringComparison.Ordinal) < 0)
                {
                    logger.Warn($"Potentially unsupported .ASE model (not generated by Q3Map2): '{asset.FullPath}'");
                }
            }
            else if (span.ContainsWordFollowedByWhitespace("*BITMAP"))
            {
                if (span.TryReadPastWhitespace(out var token) &&
                    !token.Equals("\"NOSHADER\"", StringComparison.OrdinalIgnoreCase) &&
                    !token.Equals("\"default\"", StringComparison.OrdinalIgnoreCase) &&
                    !token.Equals("\"textures/common/nodraw\"", StringComparison.OrdinalIgnoreCase))
                {
                    resources.Add(Resource.Shader(token.Trim('"').ToQString(), line.ToLine()));
                }
            }
            else if (span.StartsWith("*GEOMOBJECT", StringComparison.OrdinalIgnoreCase))
            {
                break;
            }
        }

        return resources;
    }
}
